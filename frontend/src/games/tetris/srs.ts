// 테트리스 SRS(Super Rotation System) 조각/킥 테이블 (docs/games/tetris-design.md §T4).
// 외부 의존 없음 — tetris/types.ts 만 import 한다. 유일한 소비자는 engine.ts.
//
// 좌표계: x = 열(오른쪽 +), y = 행(**아래쪽 +**).
// SRS 원본 표는 y 가 위로 + 라서, 여기 실린 오프셋은 전부 y 부호를 뒤집어 옮겼다
// (원본 (0,-2) = "아래로 2칸" → 여기서는 (0,+2)).
//
// 조각 모양은 3x3(I 는 4x4) 바운딩 박스의 **왼쪽 위**를 원점으로 하는 상대 좌표로 적는다.
// 이렇게 두면 회전 = rot 인덱스 교체 + 킥 오프셋 덧셈뿐이라, 회전 중심 계산이 필요 없다.

import type { PieceId } from './types';

/** 회전 상태. 0 = 스폰, 1 = 시계 1회(R), 2 = 180도, 3 = 반시계 1회(L) */
export type Rot = 0 | 1 | 2 | 3;
/** 회전 방향. 1 = 시계, -1 = 반시계, 2 = 180도 */
export type RotDir = 1 | -1 | 2;
/** [x, y] 상대 좌표 한 쌍 */
export type Cell = [number, number];

/** rot 방향을 더해 다음 회전 상태를 구한다(음수 모듈러 주의) */
export function rotateBy(rot: Rot, dir: RotDir): Rot {
  return (((rot + dir) % 4) + 4) % 4 as Rot;
}

