/** 킥 테이블 원본(테스트·디버그용 공개). O 는 킥이 없다. */
export const KICKS = {
  jlstz: { ...JLSTZ_90, ...JLSTZ_180 } as Record<string, Cell[]>,
  i: { ...I_90, ...I_180 } as Record<string, Cell[]>,
  o: NO_KICK,
};

/**
 * from → to 회전에 시도할 킥 오프셋 목록. 반환 배열의 **인덱스 4(5번째)** 로 들어가면
 * T-스핀은 무조건 정식으로 쳐준다(설계서 §T4). O 는 항상 [[0,0]] 하나뿐.
 */
export function kicksFor(id: PieceId, from: Rot, to: Rot): Cell[] {
  if (id === 4) return NO_KICK;                       // O: 회전해도 모양이 같아 킥 자체가 무의미
  const key = `${from}${to}`;
  const table = id === 1 ? KICKS.i : KICKS.jlstz;     // I 만 전용 표
  return table[key] || NO_KICK;
}
